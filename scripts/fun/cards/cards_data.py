import itertools as _it
import random as _rnd


def _services(cat):
    pool = POOLS[cat]
    assert len(pool) == len(set(pool)) == 14
    combos = [c for n in (3, 4) for c in _it.combinations(pool, n)]
    _rnd.Random(cat).shuffle(combos)
    out, seen = [], set()
    for c in combos:
        if frozenset(c) in seen:
            continue
        seen.add(frozenset(c)); out.append(list(c))
        if len(out) == 50:
            break
    return out


