    heading(d, "가족 구성원")
    l, t, r, b = d.rect
    n, gap = len(members), 0.25
    pw = (r - l - gap * (n - 1)) / n
    for k, (role, lines) in enumerate(members):
        person(d, l + k * (pw + gap), t, pw, b - t, role, lines)
    heading(d, "우리 가족 이야기")
    timeline(d, steps)
    heading(d, "우리 가족의 약속")
    rows(d, [(f"약속 {k + 1}", p_) for k, p_ in enumerate(promises)], h_each=1.1, size=17)
