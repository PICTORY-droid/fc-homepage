def talk_flavor(i):
    return TALK[i % 5][0]


def build_talk(path, i, pal, message):
    fl, toc, points, cmp_, heads = TALK[i % 5]
    d = new(i, pal, f"{fl} 발표 템플릿")
    cover(d, "발표 제목을 입력하세요", [f"{fl} · 발표자 이름", "2026. 00. 00"], message)
    heading(d, "목차")
    rows(d, [(t, "한 줄로 내용을 적어 주세요") for t in toc], h_each=1.0)
    heading(d, "핵심 메시지")
    l, t, r, b = d.rect
    d.text(l, t, r - l, 1.3, "한 문장으로 말하면 — 여기에 핵심 메시지를 입력하세요", size=26, bold=True, color=pal["dark"], align="c", anchor="m", name="핵심 문장")
    cards(d, [(pt, ["내용을 입력하세요", "내용을 입력하세요"]) for pt in points], y=t + 1.6, h=3.3)
    heading(d, "한눈에 비교")
    two_col(d, (cmp_[0], _rows_text(3)), (cmp_[1], _rows_text(3)))
    heading(d, "일정·현황")
    l, t, r, b = d.rect
    d.table(l, t, r - l, [heads] + [[f"{k}", "내용 입력", "", ""] for k in range(1, 6)], row_h=0.7, size=15, first_col=True)
    cover(d, "감사합니다", ["문의 · 연락처를 입력하세요"], "들어 주셔서 고맙습니다")
    d.save(path)


