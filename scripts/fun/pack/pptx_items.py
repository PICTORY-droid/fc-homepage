def new(i, pal, title, size="wide"):
    style = (i // 5 + 3 * (i % 5)) % 10  # (프레임, 구성) 조합이 50종 모두 다르다
    return Deck(pal, style, i, size, title)


def _rows_text(n, text="내용을 입력하세요"):
    return [text] * n


