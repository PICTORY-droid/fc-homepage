import colorsys

# (이름, 색상 H(0~360), 채도 S(0~1))  — 짙은 남색·청록·숲색·자두색·포도주색·세피아·슬레이트 …
TONES = [
    ("미드나이트", 222, .52), ("네이비", 215, .55), ("코발트", 224, .50), ("스틸블루", 208, .38), ("잉크블루", 232, .46),
    ("딥틸", 184, .55), ("피콕", 192, .50), ("파인", 168, .44), ("포레스트", 148, .40), ("올리브그린", 112, .30),
    ("세이지", 140, .24), ("슬레이트", 214, .16), ("그래파이트", 210, .08), ("차콜", 220, .12), ("스톤", 36, .10),
    ("플럼", 288, .34), ("아이리스", 262, .36), ("모브", 300, .20), ("버건디", 345, .46), ("와인", 352, .40),
    ("세피아", 28, .30), ("에스프레소", 22, .26), ("올드골드", 42, .38), ("인디고", 244, .44), ("오션그레이", 200, .22),
]
SANS = "맑은 고딕"
SERIF = "바탕"


def _hex(h, s, l):
    r, g, b = colorsys.hls_to_rgb(h / 360, l, s)
    return f"{round(r * 255):02X}{round(g * 255):02X}{round(b * 255):02X}"


def skin(idx, head_font=SANS, body_font=SANS):
    name, h, s = TONES[idx % len(TONES)]
    return dict(name=name, idx=idx % len(TONES), dark=_hex(h, s, .22), mid=_hex(h, s * .85, .38), soft=_hex(h, min(s, .45) * .55, .955),
                tint=_hex(h, min(s, .45) * .5, .90), line=_hex(h, min(s, .3) * .6, .80), gray="8A929C", hint="A9B0B8",
                head=head_font, body=body_font)
