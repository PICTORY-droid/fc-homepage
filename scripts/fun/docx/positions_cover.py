def build(pid):
    title, sub, pal, head, info, qs = COVERS[pid]
    f = Form(title, pal)
    f.heading(head, "자기소개서", sub)
    f.table(info, row_px=30)
    used = 110
    for i, (q, hint, h) in enumerate(qs, 1):
        need = 38 + h
        if used + need > BUDGET:
            f.new_page(); used = 0
        f.q(i, q, hint); f.box(h)
        used += need
    f.sign(False)
    return f
